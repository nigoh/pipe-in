def _section_lines(lines: list[str], heading: str) -> range:
    """lines（ファイルの全部の行）のうち、見出しが heading で始まる節の行の番号（見出しの次の行から、囲みの外の次の # か ## の見出しの手前まで）。"""
    marked = _with_fences("\n".join(lines))
    start = next(i for i, (ln, outside) in enumerate(marked) if outside and ln.startswith(heading))
    end = next((i for i, (ln, outside) in enumerate(marked) if i > start and outside and re.match(r"#{1,2} ", ln)), len(lines))
    return range(start + 1, end)


