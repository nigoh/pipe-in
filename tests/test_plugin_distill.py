# ---- 補助：節の読み方と決まりの検査 ------------------------------------------------------------------------------


def _with_fences(text: str) -> list[tuple[str, bool]]:
    """(行, 囲み（```）の外か)。囲みの中の # の行を見出しと読まないため。囲みの印の行は外ではない扱い。"""
    out: list[tuple[str, bool]] = []
    inside = False
    for ln in text.splitlines():
        if ln.lstrip().startswith("```"):
            out.append((ln, False))
            inside = not inside
            continue
        out.append((ln, not inside))
    return out


def rule_section(root: Path, key: str, sec: str) -> str | None:
    """root（plugin/ と同じ形の場所）の下の、key のファイルの節 sec の字。節が無ければ None。
    sec が「節@語」なら、その節のうち「語」を含む行だけ（そういう行が無ければ None）。"""
    base, at, anchor = sec.partition("@")
    if at:
        text = rule_section(root, key, base)
        hits = [ln for ln in text.splitlines() if anchor in ln] if text is not None else []
        return "\n".join(hits) if hits else None
    path = root / FILES[key]
    if key == "rules":
        fields, body = {}, path.read_text(encoding="utf-8")
    else:
        fields, body = frontmatter(path)
    if sec == "前書き":
        return fields.get("description")
    lines = _with_fences(body)
    if sec == "頭":
        head: list[str] = []
        for ln, outside in lines:
            if outside and ln.startswith("## "):
                break
            head.append(ln)
        return "\n".join(head)
    start = next((i for i, (ln, outside) in enumerate(lines) if outside and ln.startswith(sec)), None)
    if start is None:
        return None
    out: list[str] = []
    for ln, outside in lines[start + 1 :]:
        if outside and re.match(r"#{1,2} ", ln):
            break
        out.append(ln)
    return "\n".join(out)


def rule_problem(root: Path, rule: tuple[str, str, str, str, tuple[str, ...]]) -> tuple[str, str, str, tuple[str, ...]] | None:
    """1 行の決まりの欠け：(ID, ファイルの鍵, 節, 無い目印)。節が無ければ目印を全部欠けとする。欠けが無ければ None。"""
    rid, key, sec, _, marks = rule
    text = rule_section(root, key, sec)
    missing = marks if text is None else tuple(m for m in marks if m not in text)
    return (rid, key, sec, missing) if missing else None


