def grader_hits(fm: dict, words: tuple[str, ...], extra: str) -> bool:
    """採点（regex か tool_used）が、語でできた返事の文字か道具の入力に当たるか。"""
    kind = fm.get("type")
    if kind == "regex":
        text = " ".join([*words, *([extra] if extra else [])])
        return re.search(fm["pattern"], text, re.I if fm.get("flags") == "i" else 0) is not None
    if kind == "tool_used":
        field = {"Bash": "command", "Agent": "subagent_type"}[fm["tool"]]
        tool_input = json.dumps({field: " ".join(words)}, ensure_ascii=False)
        return re.search(fm["input_match"], tool_input) is not None
    raise AssertionError(f"採点の語の表が扱わない型: {kind}")


def grader_word_problems(row: tuple[str, tuple[str, ...], str, str, str]) -> list[str]:
    """採点の語の表の 1 行が採点とずれていないか：語で当たり、どの語を 1 つ抜いても当たらない。"""
    skill, words, case, gfile, extra = row
    found = [fm for g, fm, _ in _graders(case) if g.name == gfile]
    if not found:
        return [f"{case}/graders/{gfile} が無い"]
    fm = found[0]
    problems: list[str] = []
    if not grader_hits(fm, words, extra):
        problems.append(f"{skill} の語 {list(words)} が {case}/{gfile} に当たらない")
    for i, word in enumerate(words):
        rest = words[:i] + words[i + 1 :]
        if grader_hits(fm, rest, extra):
            problems.append(f"{skill} の語「{word}」を抜いても {case}/{gfile} に当たる（効いていない）")
    return problems


